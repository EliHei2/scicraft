#!/usr/bin/env python3
"""Regenerate THIRD_PARTY.md at the repository root from the notes each skill carries.

Every skill that builds on someone else's work has its own THIRD_PARTY.md (and a LICENSE file when text or code
was copied). This script gathers them into one file so a reader can see all outside material in one place.
Run it after changing any skill's note:

    python3 tools/build_third_party.py            # write THIRD_PARTY.md
    python3 tools/build_third_party.py --check    # exit 1 when the root file is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEAD = """# Third-party material

This package was written for the author's own projects. Some skills build on other people's work. Each such
skill carries a `THIRD_PARTY.md` in its own folder, and a `LICENSE` file when text or code was copied. This file
gathers those notes. It is generated by `tools/build_third_party.py`; edit the note in the skill folder, then run
the script.

Material that was copied keeps its own license and notice, and that notice travels with any copy of the skill.
Everything else is credited as a source of method, values or inspiration, and no code or text was copied.

## Skills that carry a note

| Plugin | Skill | Copied material with its own license |
|---|---|---|
"""


def main():
    notes = sorted(ROOT.glob("plugins/*/skills/*/THIRD_PARTY.md"))
    rows, body = [], []
    for f in notes:
        skill = f.parent
        plugin = skill.parent.parent.name
        lic = sorted(p.name for p in skill.iterdir() if re.match(r"(LICENSE|NOTICE)", p.name))
        rows.append(f"| `{plugin}` | `{skill.name}` | {', '.join(f'`{n}`' for n in lic) if lic else 'none'} |")
        text = f.read_text(encoding="utf-8").strip()
        text = re.sub(r"\A# [^\n]*\n+", "", text)                      # drop the note's own title
        text = re.sub(r"(?m)^(#+) ", lambda m: "#" + m.group(1) + "# ", text)  # push headings two levels down
        rel = f.relative_to(ROOT)
        body.append(f"## `{skill.name}` ({plugin})\n\nSource note: [`{rel}`]({rel})\n\n{text}\n")
    out = HEAD + "\n".join(rows) + "\n\n" + "\n".join(body)
    dest = ROOT / "THIRD_PARTY.md"
    if "--check" in sys.argv:
        if not dest.exists() or dest.read_text(encoding="utf-8") != out:
            print("THIRD_PARTY.md is out of date; run tools/build_third_party.py")
            sys.exit(1)
        print("THIRD_PARTY.md is up to date")
        return
    dest.write_text(out, encoding="utf-8")
    print(f"wrote THIRD_PARTY.md from {len(notes)} skill notes ({len(out.splitlines())} lines)")


if __name__ == "__main__":
    main()
