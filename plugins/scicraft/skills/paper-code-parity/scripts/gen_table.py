#!/usr/bin/env python3
"""Write a results table as a LaTeX fragment generated from the records, so no cell is ever typed by hand.

The fragment holds the body rows and is self-terminating: its last line is \\bottomrule, and its first row never
starts with \\rowcolor. The main file holds \\begin{tabular}{...}, \\toprule, the column heads, \\midrule,
\\input{tables/<stem>.tex} and \\end{tabular}; the script prints the head line to paste. (Ported convention:
TeX Live 2025 raises "Misplaced \\noalign" when \\bottomrule in the main file follows an \\input-ed row, and the
same error comes from \\toprule or \\rowcolor at the start of an \\input-ed fragment.) A sidecar JSON with the
same stem holds the heads and the cell values, so another renderer (a docx, a website) reads the same table.

Spec file (JSON):

    {
      "records": "records/main.json",            # relative to the spec file
      "rows": "methods",                          # path to a dict {row_id: {...}} or a list of dicts
      "row_order": ["ours", "vit_b", "resnet50"], # optional; default: as in the records
      "label": {"key": "name"},                   # row label column: a key in each row, or "id" for the row id
      "columns": [
        {"key": "acc",    "head": "Accuracy",  "digits": 3, "best": "max"},
        {"key": "ece",    "head": "ECE",       "digits": 3, "best": "min"},
        {"key": "params", "head": "Params (M)", "digits": 1}
      ],
      "missing": "pending"                        # text for a cell with no record
    }

"best" sets the best value of that column in bold. Bold is applied to every column by the same rule, so the
emphasis never depends on which method wins (ties are all bold). Numbers use gen_macros.py's house format.

Usage:
    python3 gen_table.py --spec table_main.json --out tables/tab_main.tex

Standard library only. Python 3.9 or later.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_macros import Missing, num, walk  # noqa: E402

TEX_ESC = {"_": r"\_", "&": r"\&", "%": r"\%", "#": r"\#"}


def esc(s: str) -> str:
    return "".join(TEX_ESC.get(ch, ch) for ch in str(s))


def rows_of(data, spec) -> list[tuple[str, dict]]:
    rows = walk(data, spec.get("rows", ""))
    pairs = list(rows.items()) if isinstance(rows, dict) else [(str(i), r) for i, r in enumerate(rows)]
    order = spec.get("row_order")
    if order:
        have = dict(pairs)
        missing = [r for r in order if r not in have]
        if missing:
            raise SystemExit(f"row_order names rows the records do not have: {missing}")
        extra = [k for k, _ in pairs if k not in order]
        if extra:
            print(f"note: rows in the records but not in row_order are left out: {extra}")
        pairs = [(r, have[r]) for r in order]
    return pairs


def build(spec_path: Path) -> tuple[str, dict]:
    spec = json.loads(spec_path.read_text())
    data = json.loads((spec_path.parent / spec["records"]).read_text())
    cols, miss = spec["columns"], spec.get("missing", "pending")
    label = spec.get("label", {"key": "id"})
    pairs = rows_of(data, spec)

    values: dict = {}
    for rid, row in pairs:
        for c in cols:
            try:
                v = walk(row, c["key"])
            except Missing:
                v = None
            values[(rid, c["key"])] = v

    best: dict = {}
    for c in cols:
        if c.get("best") in ("max", "min"):
            vs = [values[(rid, c["key"])] for rid, _ in pairs if isinstance(values[(rid, c["key"])], (int, float))]
            if vs:
                best[c["key"]] = max(vs) if c["best"] == "max" else min(vs)

    def fmt(c, v) -> str:
        if v is None:
            return miss
        if not isinstance(v, (int, float)) or isinstance(v, bool):
            return esc(v)
        s = num(v * c.get("scale", 1), int(c.get("digits", 3)), bool(c.get("sign")), bool(c.get("lead0")))
        return rf"\textbf{{{s}}}" if c["key"] in best and v == best[c["key"]] else s

    head = " & ".join([esc(label.get("head", ""))] + [esc(c["head"]) for c in cols]) + r" \\"
    lines = []
    side = {"head_tex": head, "columns": [c["head"] for c in cols], "rows": []}
    for rid, row in pairs:
        name = rid if label.get("key", "id") == "id" else row.get(label["key"], rid)
        cells = [fmt(c, values[(rid, c["key"])]) for c in cols]
        lines.append(" & ".join([esc(name)] + cells) + r" \\")
        side["rows"].append({"id": rid, "label": name, "values": [values[(rid, c["key"])] for c in cols]})
    lines.append(r"\bottomrule")
    frag = "% Generated by gen_table.py from " + spec_path.name + ". Do not edit by hand.\n" + "\n".join(lines) + "\n"
    assert not lines[0].lstrip().startswith((r"\rowcolor", r"\toprule")), "a fragment must not start with \\rowcolor"
    assert lines[-1] == r"\bottomrule"
    return frag, side


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--spec", type=Path, required=True, help="JSON table spec")
    p.add_argument("--out", type=Path, required=True, help="fragment to write, e.g. tables/tab_main.tex")
    a = p.parse_args()
    frag, side = build(a.spec)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(frag)
    a.out.with_suffix(".json").write_text(json.dumps(side, indent=1) + "\n")
    n_missing = sum(1 for r in side["rows"] for v in r["values"] if v is None)
    print(f"wrote {a.out} and {a.out.with_suffix('.json').name}: {len(side['rows'])} rows x {len(side['columns'])} "
          f"columns, {n_missing} cells without a record")
    print("head for the main file, between \\toprule and \\midrule:\n  " + side["head_tex"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
