#!/usr/bin/env python3
"""Write every number the prose or a caption quotes as a LaTeX macro, read from the result records.

The text then says \\AccOurs instead of 0.912, and a rebuild after new records land changes every sentence and
caption at once. A value whose record or key does not exist yet is written as the word "pending" (or the build
fails with --strict), so a missing result is visible on the page and is never estimated.

Spec file (JSON): one entry per macro. The name must be letters only (a TeX control word).

    {
      "records": "records",                      # optional; folder the "file" paths are relative to
      "macros": {
        "AccOurs":   {"file": "main.json", "path": "ours.acc", "digits": 3},
        "DeltaAbl":  {"file": "ablation.json", "path": "no_aug.delta", "digits": 3, "sign": true},
        "NRuns":     {"file": "main.json", "path": "n_seeds", "digits": 0},
        "BestBase":  {"file": "main.json", "path": "best_baseline", "text": true},
        "AccPct":    {"file": "main.json", "path": "ours.acc", "digits": 1, "scale": 100}
      }
    }

"path" walks dicts by key and lists by integer index, separated by dots. Number format (the house format the
macros were ported from): fixed digits, leading zero dropped below 1 (.912), minus and plus set as $-$ / $+$.
Pass "lead0": true on an entry, or --lead0 for all, to keep the zero (0.912).

Usage:
    python3 gen_macros.py --spec macros_spec.json --out tables/macros.tex
    python3 gen_macros.py --spec macros_spec.json --print        # show, write nothing

Standard library only. Python 3.9 or later.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

PENDING = "pending"
NAME = re.compile(r"^[A-Za-z]+$")
HEADER = "% Generated by gen_macros.py from {spec}. Do not edit by hand: change the records and rebuild.\n"


class Missing(Exception):
    """The record file or a key on the path does not exist (yet)."""


def num(v: float, digits: int = 3, sign: bool = False, lead0: bool = False) -> str:
    """House number format: fixed digits, no leading zero below 1 unless lead0, TeX minus and plus."""
    s = f"{v:+.{digits}f}" if sign else f"{v:.{digits}f}"
    if not lead0 and abs(v) < 1 and digits > 0:
        s = s.replace("0.", ".", 1)
    return s.replace("-", "$-$").replace("+", "$+$")


def walk(obj: Any, path: str) -> Any:
    """Follow a dotted path through dicts (by key) and lists (by integer index)."""
    cur = obj
    for part in path.split(".") if path else []:
        if isinstance(cur, list):
            try:
                cur = cur[int(part)]
            except (ValueError, IndexError):
                raise Missing(part)
        elif isinstance(cur, dict):
            if part not in cur:
                raise Missing(part)
            cur = cur[part]
        else:
            raise Missing(part)
    if cur is None:
        raise Missing(path)
    return cur


def load_spec(spec_path: Path) -> tuple[dict, Path]:
    spec = json.loads(spec_path.read_text())
    root = spec_path.parent / spec.get("records", ".")
    macros = spec.get("macros", {})
    bad = [k for k in macros if not NAME.match(k)]
    if bad:
        raise SystemExit(f"macro names must be letters only (TeX control words): {bad}")
    return macros, root


def render(entry: dict, root: Path, lead0_all: bool, cache: dict) -> str:
    """One macro's text, or raise Missing."""
    f = root / entry["file"]
    if f not in cache:
        if not f.is_file():
            raise Missing(str(f))
        cache[f] = json.loads(f.read_text())
    v = walk(cache[f], entry.get("path", ""))
    if entry.get("text"):
        return str(v)
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise SystemExit(f"{entry['file']}:{entry.get('path')} is {v!r}, not a number; mark the entry \"text\": true")
    v = v * entry.get("scale", 1)
    digits = int(entry.get("digits", 3))
    if digits == 0:
        return (f"{v:+.0f}" if entry.get("sign") else f"{v:.0f}").replace("-", "$-$").replace("+", "$+$")
    return num(v, digits, bool(entry.get("sign")), bool(entry.get("lead0", lead0_all)))


def build(spec_path: Path, lead0: bool = False, strict: bool = False) -> tuple[dict, list]:
    """Return ({name: text}, [names that are pending])."""
    macros, root = load_spec(spec_path)
    out, pending, cache = {}, [], {}
    for name, entry in macros.items():
        try:
            out[name] = render(entry, root, lead0, cache)
        except Missing as e:
            if strict:
                raise SystemExit(f"\\{name}: no record ({entry['file']} : {entry.get('path')}, missing {e})")
            out[name] = PENDING
            pending.append(name)
    return out, pending


def to_tex(macros: dict, spec_name: str) -> str:
    body = "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(macros.items()))
    return HEADER.format(spec=spec_name) + body


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--spec", type=Path, required=True, help="JSON spec: macro name -> record file and key path")
    p.add_argument("--out", type=Path, help="macros .tex file to write (e.g. tables/macros.tex)")
    p.add_argument("--print", action="store_true", help="print the macros instead of writing")
    p.add_argument("--lead0", action="store_true", help="keep the leading zero below 1 (0.912) for every entry")
    p.add_argument("--strict", action="store_true", help="fail when a record is missing instead of writing 'pending'")
    a = p.parse_args()
    if not a.out and not a.print:
        p.error("give --out or --print")
    macros, pending = build(a.spec, a.lead0, a.strict)
    tex = to_tex(macros, a.spec.name)
    if a.print:
        sys.stdout.write(tex)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(tex)
        print(f"wrote {a.out}: {len(macros)} macros, {len(pending)} pending" + (f" ({', '.join(pending)})" if pending else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
