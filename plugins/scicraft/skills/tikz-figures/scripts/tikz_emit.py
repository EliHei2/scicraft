#!/usr/bin/env python3
"""Emit TikZ fragments from geometry that real code computed, plus the numbers it shows.

The rule this serves: a tree, a partition, a graph or a point cloud in a concept figure
is generated by the method's own code on a fixed-seed input, never drawn by hand. A
hand-drawn tree reads as invented, and a hand-drawn partition that differs from what the
code computes misstates the method.

Two parts:

  1. A small library of emitters (import it from your own gen_<figure>.py):
       points(xy, style, r_pt)           \\fill[style] (x,y) circle (r);
       rects(boxes, style)               \\draw[style] (x0,y0) rectangle (x1,y1);
       segments(pairs, style)            \\draw[style] (a) -- (b);
       smooth_cycle(xy, fill, opacity)   \\fill ... plot[smooth cycle] (space separated)
       tree(nodes, edges, ...)           nodes as tnint/tnleaf, edges as tedge, a traced path
       write_frag(path, lines), write_facts(path, dict)
     All coordinates are written in the local frame you pass (default [-1,1]^2), so a
     fragment drops into any \\begin{scope}[shift=..., x=..cm, y=..cm].

  2. A worked example (the CLI below): an adaptive quadtree built on a seeded clustered
     point set, emitted as the spatial partition (frag_partition.tex) and as the tree it
     is (frag_tree.tex), with one point's address path traced in both, and the counts in
     facts.json. Replace build_partition() with an import of YOUR backend function and
     keep the emitters: the figure then shows exactly what your code does.

Standard library only.

Usage:
    python3 tikz_emit.py --out frags/                  # the quadtree example
    python3 tikz_emit.py --out frags/ --n 50 --capacity 4 --seed 3 --preamble preamble.tex
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

# ---------------------------------------------------------------- emitters


def f3(v: float) -> str:
    return f"{v:.3f}"


def points(xy, style: str, r_pt: float = 0.9) -> list[str]:
    return [f"\\fill[{style}] ({f3(x)},{f3(y)}) circle ({r_pt}pt);" for x, y in xy]


def rects(boxes, style: str) -> list[str]:
    return [f"\\draw[{style}] ({f3(a)},{f3(b)}) rectangle ({f3(c)},{f3(d)});" for a, b, c, d in boxes]


def segments(pairs, style: str) -> list[str]:
    return [f"\\draw[{style}] ({f3(a[0])},{f3(a[1])}) -- ({f3(b[0])},{f3(b[1])});" for a, b in pairs]


def smooth_cycle(xy, fill: str, opacity: float = 1.0, tension: float = 0.6) -> str:
    path = " ".join(f"({f3(x)},{f3(y)})" for x, y in xy)  # space separated, never "--"
    return f"\\fill[{fill}, opacity={opacity}] plot[smooth cycle, tension={tension}] coordinates {{{path}}};"


def tree(nodes: dict, edges: list, highlight: set | None = None, ramp: bool = True,
         node_mm: float = 4.4) -> list[str]:
    """nodes: id -> (x, y, depth, is_leaf); edges: (parent, child). Depth tints from the ramp."""
    highlight = highlight or set()
    size = f"minimum size={node_mm}mm"
    out = []
    for a, b in edges:
        sty = "tpath" if a in highlight and b in highlight else "tedge"
        out.append(f"\\draw[{sty}] ({f3(nodes[a][0])},{f3(nodes[a][1])}) -- ({f3(nodes[b][0])},{f3(nodes[b][1])});")
    for nid, (x, y, depth, leaf) in nodes.items():
        if nid in highlight:
            sty = f"tnpath, {size}"
        else:
            fill = f"ramp{min(1 + depth, 8)}" if ramp else "cloud"
            sty = f"{'tnleaf' if leaf else 'tnint'}, fill={fill}, {size}"
        out.append(f"\\node[{sty}] at ({f3(x)},{f3(y)}) {{}};")
    return out


def write_frag(path: Path, lines: list[str]) -> None:
    path.write_text("\n".join(lines) + "\n")


def write_facts(path: Path, facts: dict) -> None:
    path.write_text(json.dumps(facts, indent=2) + "\n")


# ---------------------------------------------------------------- worked example


def clustered_points(n: int, seed: int) -> list[tuple[float, float]]:
    rng = random.Random(seed)
    centers = [(rng.uniform(-0.6, 0.6), rng.uniform(-0.6, 0.6)) for _ in range(3)]
    pts = []
    while len(pts) < n:
        cx, cy = rng.choice(centers)
        x, y = rng.gauss(cx, 0.18), rng.gauss(cy, 0.18)
        if abs(x) < 0.98 and abs(y) < 0.98:
            pts.append((x, y))
    return pts


def build_partition(pts, capacity: int, max_depth: int = 6):
    """Adaptive quadtree: split a cell while it holds more than `capacity` points.
    REPLACE this with an import of the method's own partition function."""
    nodes, edges, cells = {}, [], []

    def rec(nid, box, idx, depth):
        x0, y0, x1, y1 = box
        leaf = len(idx) <= capacity or depth == max_depth
        nodes[nid] = {"box": box, "depth": depth, "leaf": leaf, "idx": idx}
        cells.append(box)
        if leaf:
            return
        mx, my = (x0 + x1) / 2, (y0 + y1) / 2
        quads = [(x0, my, mx, y1), (mx, my, x1, y1), (x0, y0, mx, my), (mx, y0, x1, my)]
        for q, (a, b, c, d) in enumerate(quads):
            sub = [i for i in idx if a <= pts[i][0] < c and b <= pts[i][1] < d]
            cid = f"{nid}{q}"
            edges.append((nid, cid))
            rec(cid, (a, b, c, d), sub, depth + 1)

    rec("r", (-1.0, -1.0, 1.0, 1.0), list(range(len(pts))), 0)
    return nodes, edges, cells


def layout_tree(nodes, edges, spacing=0.36, dy=0.7):
    """Leaves `spacing` cm apart in depth-first order, levels `dy` cm apart; parents centered."""
    children = {}
    for a, b in edges:
        children.setdefault(a, []).append(b)
    leaves = []

    def dfs(n):
        if not children.get(n):
            leaves.append(n)
        for c in children.get(n, []):
            dfs(c)

    dfs("r")
    xs = {leaf: spacing * i for i, leaf in enumerate(leaves)}

    def place(n):
        if n not in xs:
            xs[n] = sum(place(c) for c in children[n]) / len(children[n])
        return xs[n]

    place("r")
    return {n: (xs[n], -nodes[n]["depth"] * dy, nodes[n]["depth"], nodes[n]["leaf"]) for n in nodes}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Emit TikZ fragments of a partition and its tree from real code.")
    ap.add_argument("--out", required=True, help="output folder")
    ap.add_argument("--n", type=int, default=50, help="points in the toy set (default 50)")
    ap.add_argument("--capacity", type=int, default=4, help="max points per leaf (default 4)")
    ap.add_argument("--seed", type=int, default=3, help="seed of the toy set (default 3)")
    ap.add_argument("--trace", type=int, default=0, help="index of the point whose address is traced")
    ap.add_argument("--node-mm", type=float, default=2.6, help="tree node size in mm (default 2.6)")
    ap.add_argument("--preamble", help="also write fig.tex: preamble + both panels, fragments inlined")
    args = ap.parse_args(argv)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    pts = clustered_points(args.n, args.seed)
    nodes, edges, cells = build_partition(pts, args.capacity)
    path = [n for n in nodes if args.trace in nodes[n]["idx"]]  # root-to-leaf address of the point
    leaf = max(path, key=len)

    part = rects([nodes[n]["box"] for n in nodes if nodes[n]["leaf"]], "celledge")
    part += rects([nodes[leaf]["box"]], "tcelledge")
    part += points(pts, "ptdot", 0.9)
    part += points([pts[args.trace]], "contrast", 1.5)
    write_frag(out / "frag_partition.tex", part)

    spacing = (args.node_mm + 1.0) / 10  # one node plus 1 mm of air, in cm
    lay = layout_tree(nodes, edges, spacing=spacing)
    write_frag(out / "frag_tree.tex", tree(lay, edges, highlight=set(path), node_mm=args.node_mm))

    depth = max(v["depth"] for v in nodes.values())
    n_leaf = sum(1 for v in nodes.values() if v["leaf"])
    write_facts(out / "facts.json", {"generator": "adaptive quadtree (example backend)", "seed": args.seed,
                                     "n_points": args.n, "capacity": args.capacity, "depth": depth,
                                     "n_nodes": len(nodes), "n_leaves": n_leaf,
                                     "traced_point": args.trace, "address": leaf[1:]})
    if args.preamble:
        pre = Path(args.preamble).read_text().rstrip()
        body = ["\\begin{tikzpicture}[base]",
                "\\begin{scope}[x=1.6cm, y=1.6cm]", "\\draw[frame] (-1,-1) rectangle (1,1);",
                (out / "frag_partition.tex").read_text(), "\\end{scope}",
                "\\begin{scope}[shift={(2.6,1.2)}, x=1cm, y=1cm]", (out / "frag_tree.tex").read_text(),
                "\\end{scope}",
                "\\end{tikzpicture}", "\\end{document}"]
        (out / "fig.tex").write_text(pre + "\n" + "\n".join(body) + "\n")
    print(f"ok  {args.n} points, {len(nodes)} nodes, {n_leaf} leaves, depth {depth}, "
          f"traced point {args.trace} at address {leaf[1:] or '(root)'}")
    print(f"ok  wrote frag_partition.tex, frag_tree.tex, facts.json" + (", fig.tex" if args.preamble else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
